-- Stock movements: every change to a product's stock, with who made it and why. A product's
-- stock_quantity is the balance_after of its latest movement; products that already have stock get
-- an INITIAL movement so their history starts from the current balance.

create table tb_stock_movements (
    id bigint generated by default as identity,
    store_id bigint not null,
    product_id bigint not null,
    type varchar(20) not null check (type in ('INITIAL', 'ENTRY', 'EXIT', 'ADJUSTMENT')),
    reason varchar(30) not null check (reason in (
        'INITIAL_STOCK', 'PURCHASE', 'CUSTOMER_RETURN', 'SALE', 'LOSS', 'DAMAGE', 'INTERNAL_USE',
        'INVENTORY_COUNT', 'CORRECTION', 'OTHER')),
    -- Signed change: positive adds to stock, negative removes.
    quantity numeric(19,3) not null,
    balance_after numeric(19,3) not null,
    note varchar(500),
    created_by_user_id bigint,
    created_at timestamp(6) with time zone not null,
    primary key (id),
    constraint fk_tb_stock_movements_store foreign key (store_id) references tb_stores (id),
    -- Deleting a product deletes its history.
    constraint fk_tb_stock_movements_product foreign key (product_id) references tb_products (id) on delete cascade,
    constraint fk_tb_stock_movements_created_by foreign key (created_by_user_id) references tb_users (id) on delete set null
);

create index idx_tb_stock_movements_store_created on tb_stock_movements (store_id, created_at desc);
create index idx_tb_stock_movements_product_created on tb_stock_movements (product_id, created_at desc);

insert into tb_stock_movements (store_id, product_id, type, reason, quantity, balance_after, created_at)
select store_id, id, 'INITIAL', 'INITIAL_STOCK', stock_quantity, stock_quantity, coalesce(created_date, now())
from tb_products
where stock_quantity <> 0;
