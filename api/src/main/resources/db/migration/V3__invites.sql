-- Invites: single-use codes that let someone join a store with a preset role. Only the code's
-- SHA-256 is stored; the hash is unique across every store (the code alone finds the invite).

create table tb_invites (
    id bigint generated by default as identity,
    store_id bigint not null,
    token_hash varchar(64) not null,
    role varchar(20) not null check (role in ('ADMIN', 'MANAGER', 'CASHIER', 'STOCK')),
    created_by_user_id bigint not null,
    created_at timestamp(6) with time zone not null,
    expires_at timestamp(6) with time zone not null,
    used_at timestamp(6) with time zone,
    used_by_user_id bigint,
    revoked_at timestamp(6) with time zone,
    primary key (id),
    constraint uk_tb_invites_token_hash unique (token_hash),
    constraint fk_tb_invites_store foreign key (store_id) references tb_stores (id),
    constraint fk_tb_invites_created_by foreign key (created_by_user_id) references tb_users (id),
    constraint fk_tb_invites_used_by foreign key (used_by_user_id) references tb_users (id)
);

create index idx_tb_invites_store_id on tb_invites (store_id);
