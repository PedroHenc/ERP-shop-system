-- Purchase orders to suppliers. Items copy the product's SKU, name and unit, like sale items, so an
-- order stays readable when the catalog changes. Receiving records what actually arrived (quantity
-- and cost per item), enters it into stock and updates the products' average cost.

create table tb_purchase_orders (
    id bigint generated by default as identity,
    store_id bigint not null,
    -- Sequential per store (1, 2, 3…).
    number bigint not null,
    status varchar(20) not null check (status in ('DRAFT', 'ORDERED', 'RECEIVED', 'CANCELLED')),
    supplier_id bigint not null,
    notes varchar(1000),
    -- Sum of quantity × unit cost as ordered.
    total numeric(19,2) not null,
    -- Sum of received quantity × received cost; null until received.
    received_total numeric(19,2),
    created_by_user_id bigint,
    created_at timestamp(6) with time zone not null,
    ordered_at timestamp(6) with time zone,
    received_at timestamp(6) with time zone,
    received_by_user_id bigint,
    cancelled_at timestamp(6) with time zone,
    primary key (id),
    constraint uk_tb_purchase_orders_store_number unique (store_id, number),
    constraint fk_tb_purchase_orders_store foreign key (store_id) references tb_stores (id),
    constraint fk_tb_purchase_orders_supplier foreign key (supplier_id) references tb_suppliers (id),
    constraint fk_tb_purchase_orders_created_by foreign key (created_by_user_id) references tb_users (id) on delete set null,
    constraint fk_tb_purchase_orders_received_by foreign key (received_by_user_id) references tb_users (id) on delete set null
);

create index idx_tb_purchase_orders_store_created on tb_purchase_orders (store_id, created_at desc);

create table tb_purchase_order_items (
    id bigint generated by default as identity,
    store_id bigint not null,
    purchase_order_id bigint not null,
    product_id bigint,
    sku varchar(64) not null,
    name varchar(150) not null,
    unit_of_measure varchar(20) not null,
    quantity numeric(19,3) not null,
    unit_cost numeric(19,2) not null,
    total numeric(19,2) not null,
    received_quantity numeric(19,3),
    received_unit_cost numeric(19,2),
    primary key (id),
    constraint fk_tb_purchase_order_items_store foreign key (store_id) references tb_stores (id),
    constraint fk_tb_purchase_order_items_order foreign key (purchase_order_id) references tb_purchase_orders (id) on delete cascade,
    constraint fk_tb_purchase_order_items_product foreign key (product_id) references tb_products (id) on delete set null
);

create index idx_tb_purchase_order_items_order on tb_purchase_order_items (purchase_order_id);
create index idx_tb_purchase_order_items_product on tb_purchase_order_items (product_id);
