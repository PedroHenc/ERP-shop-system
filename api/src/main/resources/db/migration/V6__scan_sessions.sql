-- Scan sessions: a screen (e.g. "New product" on the computer) shows a QR code; a phone opens it,
-- reads a barcode with its camera and sends it here; the screen polls the session and gets the code.
-- Only the token's SHA-256 is stored; a session lives a few minutes and takes a single code.

create table tb_scan_sessions (
    id bigint generated by default as identity,
    store_id bigint not null,
    token_hash varchar(64) not null,
    created_by_user_id bigint not null,
    created_at timestamp(6) with time zone not null,
    expires_at timestamp(6) with time zone not null,
    code varchar(64),
    scanned_at timestamp(6) with time zone,
    primary key (id),
    constraint uk_tb_scan_sessions_token_hash unique (token_hash),
    constraint fk_tb_scan_sessions_store foreign key (store_id) references tb_stores (id),
    constraint fk_tb_scan_sessions_created_by foreign key (created_by_user_id) references tb_users (id) on delete cascade
);

create index idx_tb_scan_sessions_store on tb_scan_sessions (store_id);
