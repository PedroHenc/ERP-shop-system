-- Sales from the point of sale. Items copy the product's SKU, name, unit and price at the time of the
-- sale, so the history stays as sold when the catalog changes or a product is deleted. Each item's
-- stock exit is a stock movement that points back at its sale.

create table tb_sales (
    id bigint generated by default as identity,
    store_id bigint not null,
    -- Sequential per store (1, 2, 3…), what the cashier and the receipt show.
    number bigint not null,
    status varchar(20) not null check (status in ('COMPLETED', 'CANCELLED')),
    -- Sum of quantity × unit price, before any discount.
    subtotal numeric(19,2) not null,
    items_discount numeric(19,2) not null,
    -- Discount on the whole sale, after the items' discounts.
    discount numeric(19,2) not null,
    total numeric(19,2) not null,
    payment_method varchar(20) not null check (payment_method in ('CASH', 'PIX', 'DEBIT_CARD', 'CREDIT_CARD')),
    amount_paid numeric(19,2) not null,
    change_due numeric(19,2) not null,
    note varchar(500),
    created_by_user_id bigint,
    created_at timestamp(6) with time zone not null,
    cancelled_at timestamp(6) with time zone,
    cancelled_by_user_id bigint,
    cancel_reason varchar(500),
    primary key (id),
    constraint uk_tb_sales_store_number unique (store_id, number),
    constraint fk_tb_sales_store foreign key (store_id) references tb_stores (id),
    constraint fk_tb_sales_created_by foreign key (created_by_user_id) references tb_users (id) on delete set null,
    constraint fk_tb_sales_cancelled_by foreign key (cancelled_by_user_id) references tb_users (id) on delete set null
);

create index idx_tb_sales_store_created on tb_sales (store_id, created_at desc);

create table tb_sale_items (
    id bigint generated by default as identity,
    store_id bigint not null,
    sale_id bigint not null,
    product_id bigint,
    sku varchar(64) not null,
    name varchar(150) not null,
    unit_of_measure varchar(20) not null,
    quantity numeric(19,3) not null,
    unit_price numeric(19,2) not null,
    discount numeric(19,2) not null,
    total numeric(19,2) not null,
    primary key (id),
    constraint fk_tb_sale_items_store foreign key (store_id) references tb_stores (id),
    constraint fk_tb_sale_items_sale foreign key (sale_id) references tb_sales (id) on delete cascade,
    constraint fk_tb_sale_items_product foreign key (product_id) references tb_products (id) on delete set null
);

create index idx_tb_sale_items_sale on tb_sale_items (sale_id);
create index idx_tb_sale_items_product on tb_sale_items (product_id);

alter table tb_stock_movements add column sale_id bigint;
alter table tb_stock_movements add constraint fk_tb_stock_movements_sale foreign key (sale_id) references tb_sales (id) on delete set null;
