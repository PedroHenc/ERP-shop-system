-- Stores (tenants). Every existing row moves to store 1; the global uniques that must hold per
-- store become (store_id, column) composites. User e-mail and refresh-token hash stay global.

create table tb_stores (
    id bigint generated by default as identity,
    name varchar(100) not null,
    active boolean not null,
    created_at timestamp(6) with time zone not null default now(),
    primary key (id)
);

insert into tb_stores (id, name, active) overriding system value values (1, 'Loja principal', true);
