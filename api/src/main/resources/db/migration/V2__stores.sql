-- Global uniques become per store. The baseline's constraint names were generated by Hibernate,
-- so they are found by table and column. A schema grown by ddl-auto=update can hold more than one
-- single-column unique on the same column (a Hibernate uk... and Postgres's inline tb_x_col_key),
-- so every match is dropped; the migration fails if none is found.

DO $$ DECLARE c text; n int := 0; BEGIN
  FOR c IN SELECT con.conname FROM pg_constraint con
      JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = ANY (con.conkey)
     WHERE con.conrelid = 'tb_brands'::regclass AND con.contype = 'u'
       AND array_length(con.conkey, 1) = 1 AND a.attname = 'name'
  LOOP
    EXECUTE format('ALTER TABLE tb_brands DROP CONSTRAINT %I', c);
    n := n + 1;
  END LOOP;
  IF n = 0 THEN RAISE EXCEPTION 'unique constraint on tb_brands.name not found'; END IF;
END $$;
ALTER TABLE tb_brands ADD CONSTRAINT uk_brands_store_name UNIQUE (store_id, name);

